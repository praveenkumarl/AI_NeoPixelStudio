#!/usr/bin/env python3
r"""Encode web/index.html into ui_embedded.h (PROGMEM C string).

Escaping matches the original generator: printable ASCII stays literal with
backslash, quote and question mark escaped, tab/newline as \n \t, everything
else as a two-digit hex escape. Fragments wrap at 60 source characters and an
escape is never split across fragments, so per-literal C unescaping (which is
how the compiler concatenates adjacent literals) always round-trips.
"""
import re
import sys

SRC = sys.argv[1] if len(sys.argv) > 1 else "web/index.html"
DST = sys.argv[2] if len(sys.argv) > 2 else "ui_embedded.h"

with open(SRC, "rb") as f:
    data = f.read()

# Escape one byte to C source characters.
def esc(b):
    c = chr(b)
    if c == "\\":
        return "\\\\"
    if c == '"':
        return '\\"'
    if c == "?":
        return "\\?"
    if c == "\n":
        return "\\n"
    if c == "\t":
        return "\\t"
    if c == "\r":
        return "\\r"
    if 0x20 <= b < 0x7F:
        return c
    return "\\x{:02x}".format(b)

# Token stream of atomic escapes; a fragment never ends mid-escape.
tokens = []
for b in data:
    tokens.append(esc(b))

WIDTH = 60
lines = []
cur = ""
for tok in tokens:
    if len(cur) + len(tok) > WIDTH and cur:
        lines.append(cur)
        cur = ""
    cur += tok
if cur:
    lines.append(cur)

total = len(data)
header = f"""// ---------------------------------------------------------------------------
// AUTO-GENERATED by tools/build_embedded_ui.py - do not edit by hand.
//
// The complete web interface, in FLASH via PROGMEM. {total} bytes.
//
// PROGMEM is load-bearing: without it this data lands in .rodata, which the
// ESP8266 linker puts in DRAM, and the sketch fails to link with
// "section .bss is not within region dram0_0_seg".
//
// Source of truth: web/index.html. Regenerate with:
//     python tools/build_embedded_ui.py
// (tools/decode_ui.py extracts it back out for editing.)
// ---------------------------------------------------------------------------
#ifndef UI_EMBEDDED_H
#define UI_EMBEDDED_H

#include <pgmspace.h>

#define UI_EMBEDDED_LEN {total}u

// Concatenated by the compiler into one contiguous flash-resident blob.
static const char UI_EMBEDDED[] PROGMEM =
"""

with open(DST, "w", encoding="utf-8", newline="\n") as f:
    f.write(header)
    # The terminating ';' goes on the LAST content line, like the original
    # generator: every line is a complete literal, so a standalone '";' line
    # would itself be an unterminated string and break the build.
    for i, ln in enumerate(lines):
        f.write('  "' + ln + '"' + (';' if i == len(lines) - 1 else '') + '\n')
    f.write('#endif\n')

# Self-test: every line must be one well-formed C literal (the last one
# followed by ';'), so a terminator bug fails here instead of in the build.
import re
written = open(DST, encoding="utf-8").read().split("\n")
first = next(i for i, l in enumerate(written) if "UI_EMBEDDED[] PROGMEM =" in l)
endif_idx = next(i for i, l in enumerate(written) if l.strip() == "#endif")
last = endif_idx - 1
for i in range(first + 1, last + 1):
    if not re.match(r'^\s*"((?:[^"\\]|\\.)*)";?\s*$', written[i]):
        raise SystemExit(f"self-test failed: malformed fragment line {i+1}")
if not written[last].rstrip().endswith('";'):
    raise SystemExit("self-test failed: last content line must end with 'quote semicolon'")

print(f"encoded {total} bytes as {len(lines)} fragments -> {DST}")
